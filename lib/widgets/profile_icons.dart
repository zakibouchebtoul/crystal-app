class _ProfileIconPainter extends CustomPainter {
  const _ProfileIconPainter(this.parts);

  final List<_Part> parts;

  @override
  void paint(Canvas canvas, Size size) {
    canvas.scale(size.width / 24);
    for (final part in parts) {
      final paint = Paint()..color = part.color;
      if (part.stroke case final width?) {
        paint
          ..style = PaintingStyle.stroke
          ..strokeWidth = width
          ..strokeCap = StrokeCap.round
          ..strokeJoin = StrokeJoin.round;
      }
      canvas.drawPath(part.path, paint);
    }
  }

  @override
  bool shouldRepaint(_ProfileIconPainter old) => old.parts != parts;
}

